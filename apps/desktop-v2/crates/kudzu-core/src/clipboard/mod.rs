//! Clipboard history: what a copy *is*, when it happened, and how long it's kept.
//!
//! Pure logic only. The pasteboard arrives as raw `(type, bytes)` pairs per item
//! ([`PasteItem`]). This module holds the entry model; its submodules do the work:
//!
//! - `classify`: what was copied ([`classify`], [`Classified`]) and the content fingerprint.
//! - `history`: the index ([`History`]): folding repeats, secrets, pins, use.
//! - `retention`: the retention window and the entry cap ([`History::prune`]).
//! - `blob`: the raw-data encoding for exact restoration ([`encode_items`] / [`decode_items`]).
//! - [`query`], [`sections`], [`facts`]: search, grouping and labels, filled by S22.
//!
//! Entries hold metadata and a bounded text excerpt; full data lives in a blob next to the index.
//! [`History`] is persisted as `history.json`, so its JSON shape is pinned by the golden tests.

