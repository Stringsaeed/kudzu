//! The parity run's outputs: `report.md`, `report.json`, and the side-by-side `sheet.html`
//! (full-screen reference and Rune pairs for every compared screen, landmark crops for every
//! screen and gallery row).

use std::{collections::BTreeMap, fmt::Write as _, path::Path};

use serde_json::{json, Value};

use super::compare::{Kind, Row, Status};

/// A rendered scene: its PNG, viewport in points and, for a screen, the reference capture.
pub(super) struct Render {
    pub png: std::path::PathBuf,
    pub viewport: (f32, f32),
    pub reference: Option<(String, (f32, f32))>,
}

fn verdict(r: &Row) -> &'static str {
    match r.kind {
        Kind::Pending => "not yet built",
        Kind::Info => "info",
        Kind::Gated if r.failed() => "**FAIL**",
        Kind::Gated => "pass",
    }
}

fn list(r: &Row, status: Status) -> String {
    let items: Vec<String> = r
        .checks
        .iter()
        .filter(|c| c.status == status)
        .map(|c| format!("{}: {} → {}", c.prop, c.expected, c.got))
        .collect();
    if items.is_empty() {
        "-".into()
    } else {
        items.join("<br>")
    }
}

pub(super) fn markdown(rows: &[Row]) -> String {
    let failed = rows.iter().filter(|r| r.failed()).count();
    let reviews: usize = rows
        .iter()
        .map(|r| {
            r.checks
                .iter()
                .filter(|c| c.status == Status::Review)
                .count()
        })
        .sum();
    let pending = rows.iter().filter(|r| r.kind == Kind::Pending).count();
    let mut md = format!(
        "# Parity report\n\nGenerated by `cargo xtask parity`. Geometry within 2 pt, colours per 8-bit sRGB channel. \
         {} rows: {failed} failed, {pending} reference states not yet built, {reviews} properties need side-by-side review \
         (`sheet.html`).\n",
        rows.len()
    );
    let mut page = String::new();
    for r in rows {
        if r.page != page {
            page.clone_from(&r.page);
            let _ = write!(md, "\n## {page}\n\n| Theme | Item | Verdict | Failed | Passed | Needs side-by-side review |\n|---|---|---|---|---|---|\n");
        }
        let passed: Vec<&str> = r
            .checks
            .iter()
            .filter(|c| c.status == Status::Pass)
            .map(|c| c.prop.as_str())
            .collect();
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} |",
            r.theme,
            r.item,
            verdict(r),
            list(r, Status::Fail),
            passed.join(", "),
            list(r, Status::Review)
        );
    }
    md
}

pub(super) fn json(rows: &[Row]) -> Value {
    let status = |s: Status| match s {
        Status::Pass => "pass",
        Status::Fail => "fail",
        Status::Review => "review",
    };
    rows.iter()
        .map(|r| {
            json!({
                "page": r.page, "theme": r.theme, "item": r.item, "verdict": verdict(r).trim_matches('*'),
                "checks": r.checks.iter().map(|c| json!({"property": c.prop, "expected": c.expected, "got": c.got, "status": status(c.status)})).collect::<Vec<_>>(),
            })
        })
        .collect()
}

/// A crop of `src` (a 2× capture shown at points) at `r`.
fn crop(src: &str, r: [f32; 4], viewport: (f32, f32)) -> String {
    format!(
        "<div class=c style=\"width:{}px;height:{}px;background:url('{src}') -{}px -{}px/{}px {}px\"></div>",
        r[2], r[3], r[0], r[1], viewport.0, viewport.1
    )
}

fn missing(what: &str) -> String {
    format!("<div class=missing>{what}</div>")
}

/// The sheet. `pngs` is the reference PNG folder; a reference file absent from it is shown as
/// missing rather than skipped.
pub(super) fn sheet(
    rows: &[Row],
    pngs: &Path,
    renders: &BTreeMap<String, Render>,
    viewports: &BTreeMap<String, (f32, f32)>,
) -> String {
    let mut html = String::from(
        "<!doctype html><meta charset=utf-8><title>Kudzu parity</title><style>body{font:13px system-ui;margin:24px}\
         td{padding:6px 10px;vertical-align:top}.c{outline:1px dashed #f0f}.fail{color:#c00}.missing{color:#c00;font-style:italic}\
         .pair img{width:50%;border:1px solid #ccc}</style><h1>Kudzu parity: reference (Tauri, WebKit) | Rune</h1>\
         <p>Pixel equality is not a gate; this sheet is for the properties marked “needs side-by-side review”.</p>",
    );
    for (key, render) in renders {
        let Some((file, ref_vp)) = &render.reference else {
            continue;
        };
        let reference = pngs.join(file);
        let left = if reference.is_file() {
            format!("<img src=\"{}\">", reference.display())
        } else {
            missing(&format!("reference PNG missing: {}", reference.display()))
        };
        let _ = write!(
            html,
            "<h2 id=\"{key}\">{key}</h2><p>{}×{} | {}×{}</p><div class=pair>{left}<img src=\"{}\"></div><table>",
            ref_vp.0, ref_vp.1, render.viewport.0, render.viewport.1, render.png.display()
        );
        crops(
            &mut html,
            rows.iter()
                .filter(|r| format!("{}.{}", r.page, r.theme) == *key),
            pngs,
            render,
            viewports,
        );
        html += "</table>";
    }
    html += "<h2>Gallery samples</h2><table>";
    for (key, render) in renders.iter().filter(|(k, _)| k.starts_with("gallery/")) {
        crops(
            &mut html,
            rows.iter()
                .filter(|r| format!("{}.{}", r.page, r.theme) == *key),
            pngs,
            render,
            viewports,
        );
    }
    html + "</table>"
}

fn crops<'a>(
    html: &mut String,
    rows: impl Iterator<Item = &'a Row>,
    pngs: &Path,
    render: &Render,
    viewports: &BTreeMap<String, (f32, f32)>,
) {
    for r in rows {
        let Some(c) = &r.crop else { continue };
        let reference = pngs.join(&c.file);
        let ref_vp = viewports.get(&c.file).copied();
        let left = match (c.reference, ref_vp, reference.is_file()) {
            (Some(rect), Some(vp), true) => crop(&reference.display().to_string(), rect, vp),
            (Some(_), _, false) => {
                missing(&format!("reference PNG missing: {}", reference.display()))
            }
            _ => missing("not in the reference"),
        };
        let right = c.rune.map_or_else(
            || missing("not drawn by Rune"),
            |rect| crop(&render.png.display().to_string(), rect, render.viewport),
        );
        let class = if r.failed() { " class=fail" } else { "" };
        let _ = write!(
            html,
            "<tr><td{class}>{} ({})<br>{}<br><small>review: {}</small></td><td>{left}</td><td>{right}</td></tr>",
            r.item,
            r.theme,
            verdict(r),
            list(r, Status::Review)
        );
    }
}
