//! The parity run's outputs: the Markdown report and the side-by-side HTML sheet.

use std::{
    collections::HashMap,
    fmt::Write as _,
    path::{Path, PathBuf},
};

use super::{RefState, Row};

/// A crop of `png` (a 2× capture shown at points) at `r`.
fn crop(src: &str, r: [f32; 4], viewport: (f32, f32)) -> String {
    format!(
        "<div class=c style=\"width:{}px;height:{}px;background:url('{src}') -{}px -{}px/{}px {}px\"></div>",
        r[2], r[3], r[0], r[1], viewport.0, viewport.1
    )
}

pub(super) fn sheet(
    rows: &[Row],
    refs: &[RefState],
    pngs: &Path,
    renders: &HashMap<String, (PathBuf, (f32, f32))>,
    title: &str,
) -> String {
    let mut html = format!(
        "<!doctype html><meta charset=utf-8><title>{title}</title><style>body{{font:13px system-ui;margin:24px}}\
         td{{padding:6px 10px;vertical-align:middle}}.c{{outline:1px dashed #f0f}}.fail{{color:#c00}}</style>\
         <h1>{title}</h1><p>Reference (Tauri, WebKit) | Rune. Pixel equality is not a gate.</p><table>"
    );
    for r in rows {
        let Some((file, want, got)) = &r.crops else {
            continue;
        };
        let Some(st) = refs.iter().find(|s| &s.file == file) else {
            continue;
        };
        let reference = pngs.join(file);
        let Some((png, vp)) = renders.get(&format!("{}.{}", r.page, r.theme)) else {
            continue;
        };
        let class = if r.pass { "" } else { " class=fail" };
        let _ = write!(
            html,
            "<tr><td{class}>{} ({})<br>{} → {}</td><td>{}</td><td>{}</td></tr>",
            r.item,
            r.theme,
            r.expected,
            r.got,
            crop(&reference.display().to_string(), *want, st.viewport),
            crop(&png.display().to_string(), *got, *vp)
        );
    }
    html + "</table>"
}

pub(super) fn report(rows: &[Row]) -> String {
    let mut md = String::from("# Parity report\n\nGenerated by `cargo xtask parity`. Gated rows must be within 2 pt and keep the reference's background.\n\n");
    let mut page = String::new();
    for r in rows {
        if r.page != page {
            page.clone_from(&r.page);
            let _ = write!(md, "\n## {page}\n\n| Theme | Item | Expected | Rune | Δ pt | Fill (ref → Rune) | Verdict |\n|---|---|---|---|---:|---|---|\n");
        }
        let verdict = match (r.gated, r.pass) {
            (false, _) => "info",
            (true, true) => "pass",
            (true, false) => "**FAIL**",
        };
        let d = r.delta.map_or("-".into(), |d| format!("{d:.2}"));
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {d} | {} → {} | {verdict} |",
            r.theme, r.item, r.expected, r.got, r.fill.0, r.fill.1
        );
    }
    md
}
