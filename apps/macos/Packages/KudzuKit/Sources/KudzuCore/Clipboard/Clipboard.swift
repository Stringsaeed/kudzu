// Ported from kudzu-core/src/clipboard.rs
// Clipboard history: what a copy *is*, when it happened, and how long it's kept.
//
// Pure logic only. The engine reads the pasteboard as raw `(type, bytes)` pairs per item; this
// module classifies them ([`classify`]), folds repeats of the same content into one entry with
// its copy timings ([`History::ingest`]), applies the retention window ([`History::prune`]) and
// encodes the raw data for exact restoration ([`encode_items`] / [`decode_items`]).
//
// Entries hold metadata and a bounded text excerpt; full data lives in a blob next to the index.

import Foundation

/// Clipboard history: classifying copies, preserving pasteboard bytes and retention.
public enum Clipboard {
    public static let TEXT_EXCERPT_LIMIT = 2048
    public static let MAX_TIMINGS = 64
    public static let MAX_ENTRIES = 5000
    public static let DEFAULT_RETENTION_DAYS: UInt32 = 7
    public static let SECRET_RULES: UInt32 = 1
    public typealias PasteItem = [(String, Data)]

    /// Uniform type identifiers Kudzu understands, in preference order.
    public enum uti {
        public static let PLAIN_TEXT = "public.utf8-plain-text", LEGACY_TEXT = "NSStringPboardType"
        public static let RTF = "public.rtf", HTML = "public.html", URL = "public.url", FILE_URL = "public.file-url"
        public static let PNG = "public.png", TIFF = "public.tiff", JPEG = "public.jpeg", HEIC = "public.heic"
        public static let GIF = "com.compuserve.gif", WEBP = "org.webmproject.webp", PDF = "com.adobe.pdf"
        public static let IMAGES = [(PNG,"image/png"),(JPEG,"image/jpeg"),(GIF,"image/gif"),(WEBP,"image/webp"),(HEIC,"image/heic"),(TIFF,"image/tiff")]
        public static let PRIVATE_MARKERS = ["org.nspasteboard.ConcealedType","org.nspasteboard.TransientType","org.nspasteboard.AutoGeneratedType","com.agilebits.onepassword","de.petermaurer.TransientPasteboardType","com.typeit4me.clipping","Pasteboard generator type"]
    }
    public struct Classified: Equatable, Sendable {
        public var kind: ClipKind
        public var text: String?
        public var files: [String]
        public var color: String?
        public var rich: Bool
        public var imageType: String?
        public var types: [String]
        public var size: UInt64
        public var hash: UInt64
        public init(kind: ClipKind, text: String? = nil, files: [String] = [], color: String? = nil,
                    rich: Bool = false, imageType: String? = nil, types: [String] = [], size: UInt64 = 0, hash: UInt64) {
            self.kind = kind; self.text = text; self.files = files; self.color = color; self.rich = rich
            self.imageType = imageType; self.types = types; self.size = size; self.hash = hash
        }
    }
    /// Whether the source marked this copy as private or transient (see [`uti::PRIVATE_MARKERS`]).
    public static func isPrivate(_ items: [PasteItem]) -> Bool {
        items.joined().contains { t in uti.PRIVATE_MARKERS.contains { $0.isExactly(t.0) } }
    }
    /// The first `(type, data)` pair whose type has exactly these bytes (Rust `==` on `String`).
    static func find(_ items: [PasteItem], _ type: String) -> Data? { items.lazy.joined().first { $0.0.isExactly(type) }?.1 }
    /// Bundle ids of apps whose copies Kudzu never records by default (password managers).
    public static func defaultIgnoredApps() -> [String] {
        ["com.1password.1password","com.agilebits.onepassword7","com.agilebits.onepassword-osx","com.bitwarden.desktop","com.apple.keychainaccess","com.apple.Passwords","org.keepassxc.keepassxc","com.dashlane.dashlanephonefinal","com.lastpass.LastPass","in.sinew.Enpass-Desktop","com.nordsec.nordpass","me.proton.pass.electron"]
    }
    /// Decides what was copied. `nil` when there's nothing worth keeping (empty, or only whitespace).
    public static func classify(_ items: [PasteItem], sourceBundle: String? = nil) -> Classified? {
        let types = items.first?.map { $0.0 } ?? [], all = Array(items.joined())
        let size = all.reduce(UInt64(0)) { $0 + UInt64($1.1.count) }
        let rich = all.contains { t in [uti.RTF, uti.HTML, "public.rtfd", "com.apple.flat-rtfd"].contains { $0.isExactly(t.0) } }
        func classified(_ kind: ClipKind, _ text: String?, files: [String] = [], color: String? = nil, rich: Bool = false, image: String? = nil, parts: [Data]) -> Classified {
            Classified(kind: kind, text: text, files: files, color: color, rich: rich, imageType: image, types: types, size: size, hash: fnv1a(parts))
        }
        // Files: one `public.file-url` per item.
        let files = items.compactMap { $0.first { $0.0.isExactly(uti.FILE_URL) } }.compactMap { RustText.utf8String($0.1) }.compactMap(fileURLToPath)
        if !files.isEmpty { let t = files.joined(separator: "\n"); return classified(.file, t, files: files, parts: [Data("f".utf8), Data(t.utf8)]) }
        let text = (find(items, uti.PLAIN_TEXT) ?? find(items, uti.LEGACY_TEXT)).flatMap { RustText.utf8String($0) }.flatMap { RustText.trim($0).isEmpty ? nil : $0 }
        // Text wins over an image when both are present (spreadsheets put a picture of the cells
        // next to their text); a lone image is an image.
        if let text {
            let trimmed = RustText.trim(text), color = parseColor(trimmed)
            let link = isLink(trimmed) || (find(items, uti.URL) != nil && !trimmed.unicodeScalars.contains(where: RustText.isWhitespace))
            let kind: ClipKind = color != nil ? .color : link ? .link : looksLikeCode(text, sourceBundle: sourceBundle) ? .code : .text
            return classified(kind, text, color: color, rich: rich, parts: [Data("t".utf8), Data(text.utf8)])
        }
        if let image = uti.IMAGES.first(where: { type, _ in all.contains { $0.0.isExactly(type) } }), let data = find(items, image.0), !data.isEmpty {
            return classified(.image, nil, image: image.0, parts: [Data("i".utf8), data])
        }
        // Nothing at all, or only blank text.
        func textual(_ t: String) -> Bool { [uti.PLAIN_TEXT, uti.LEGACY_TEXT, "public.text"].contains { $0.isExactly(t) } || RustText.hasPrefix(t, "public.utf16") }
        if size == 0 || all.allSatisfy({ textual($0.0) }) { return nil }
        return classified(.other, nil, rich: rich, parts: [Data("o".utf8)] + all.flatMap { [Data($0.0.utf8), $0.1] })
    }
    /// 64-bit FNV-1a over several byte slices (stable across runs and platforms).
    public static func fnv1a(_ parts: [Data]) -> UInt64 {
        var h: UInt64 = 0xcbf29ce484222325
        for part in parts {
            for b in part { h = (h ^ UInt64(b)) &* 0x100000001b3 }
            // Separator, so ("ab","c") and ("a","bc") differ.
            h = (h ^ 0xff) &* 0x100000001b3
        }
        return h
    }
    /// `file:///Users/me/My%20File.txt` → `/Users/me/My File.txt`.
    public static func fileURLToPath(_ url: String) -> String? {
        var b = Array(RustText.trim(url).utf8)
        while b.last == 0 { b.removeLast() }
        guard b.starts(with: "file://".utf8) else { return nil }
        b.removeFirst(7)
        // Optional host ("localhost") before the path.
        if b.first != UInt8(ascii: "/") { guard let slash = b.firstIndex(of: UInt8(ascii: "/")) else { return nil }; b.removeFirst(slash) }
        func hex(_ c: UInt8) -> UInt8? {
            switch c { case 48...57: c - 48; case 65...70: c - 55; case 97...102: c - 87; default: nil }
        }
        var out: [UInt8] = [], i = 0
        while i < b.count {
            if b[i] == UInt8(ascii: "%") && i + 2 < b.count {
                // Rust gives up on the whole URL when the two bytes aren't UTF-8 (`from_utf8(..).ok()?`).
                guard RustText.utf8String(b[(i + 1)...(i + 2)]) != nil else { return nil }
                // `u8::from_str_radix` also takes a leading `+`.
                let hi = b[i + 1] == UInt8(ascii: "+") ? 0 : hex(b[i + 1]), lo = hex(b[i + 2])
                if let hi, let lo { out.append(hi << 4 | lo); i += 3; continue }
            }
            out.append(b[i]); i += 1
        }
        guard var path = RustText.utf8String(out) else { return nil }
        if path.utf8.count > 1 && out.last == UInt8(ascii: "/") { path = String(decoding: out.dropLast(), as: UTF8.self) }
        return path
    }
    /// A single web, mail or FTP address.
    public static func isLink(_ text: String) -> Bool {
        guard !text.isEmpty && text.utf8.count <= 4096 && !text.unicodeScalars.contains(where: RustText.isWhitespace) else { return false }
        let lower = Array(RustText.asciiLowercased(text).utf8)
        if let p = ["https://", "http://", "ftp://", "mailto:"].first(where: { lower.starts(with: $0.utf8) }) {
            let rest = lower.dropFirst(p.utf8.count)
            return !rest.isEmpty && (p == "mailto:" || rest.contains(UInt8(ascii: ".")) || rest.starts(with: "localhost".utf8))
        }
        return lower.starts(with: "www.".utf8) && lower.dropFirst(4).contains(UInt8(ascii: "."))
    }
    /// A CSS colour (`#0af`, `#0a0bfc80`, `rgb(…)`, `hsl(…)`, `oklch(…)` …), normalized for display.
    public static func parseColor(_ text: String) -> String? {
        let t = RustText.trim(text)
        guard t.utf8.count <= 64 else { return nil }
        if RustText.hasPrefix(t, "#") {
            let h = String(decoding: t.utf8.dropFirst(), as: UTF8.self)
            return [3, 4, 6, 8].contains(h.utf8.count) && Secrets.isHex(h) ? "#" + RustText.asciiLowercased(h) : nil
        }
        let lower = RustText.asciiLowercased(t), b = Array(lower.utf8)
        guard let open = b.firstIndex(of: UInt8(ascii: "(")) else { return nil }
        let name = String(decoding: b[..<open], as: UTF8.self)
        guard ["rgb", "rgba", "hsl", "hsla", "hwb", "lab", "lch", "oklab", "oklch"].contains(where: { $0.isExactly(name) }), b.last == UInt8(ascii: ")"), open < b.count - 1 else { return nil }
        let args = String(decoding: b[(open + 1)..<(b.count - 1)], as: UTF8.self)
        let numbers = args.unicodeScalars.split { $0 == "," || $0 == "/" || RustText.isWhitespace($0) }.count
        let allowed = args.unicodeScalars.allSatisfy { ("0"..."9").contains($0) || " .,%/-+edgrantu".unicodeScalars.contains($0) }
        return allowed && (3...4).contains(numbers) && args.unicodeScalars.contains(where: { ("0"..."9").contains($0) }) ? RustText.splitWhitespace(lower).joined(separator: " ") : nil
    }
    /// Apps whose text is almost always code.
    static let codeApps = ["com.microsoft.VSCode","com.microsoft.VSCodeInsiders","com.todesktop.230313mzl4w4u92","dev.zed.Zed","com.apple.dt.Xcode","com.sublimetext.4","com.panic.Nova","com.jetbrains.intellij","com.jetbrains.WebStorm","com.jetbrains.pycharm","com.apple.Terminal","com.googlecode.iterm2","dev.warp.Warp-Stable","com.mitchellh.ghostty","net.kovidgoyal.kitty","com.github.wez.wezterm"]
    static let commands = ["git ","npm ","pnpm ","yarn ","npx ","cargo ","brew ","cd ","ls ","curl ","docker ","kubectl ","sudo ","ssh ","python ","python3 ","node ","make ","export ","echo ","mkdir ","rm ","go ","bun "]
    /// Heuristic: does this text read like source code or a shell command?
    public static func looksLikeCode(_ text: String, sourceBundle: String? = nil) -> Bool {
        let t = RustText.trim(text)
        guard !t.isEmpty else { return false }
        let lines = RustText.lines(t), code = sourceBundle.map { b in codeApps.contains { $0.isExactly(b) } || RustText.hasPrefix(b, "com.jetbrains.") } ?? false
        func starts(_ s: String, _ p: String) -> Bool { RustText.hasPrefix(s, p) }
        func ends(_ s: String, _ p: String) -> Bool { RustText.hasSuffix(s, p) }
        func has(_ s: String, _ p: String) -> Bool { RustText.contains(s, p) }
        if lines.count == 1 {
            let l = lines[0]
            if starts(l, "$ ") || commands.contains(where: { starts(l, $0) }) { return true }
            if code && (has(l, "()") || ends(l, ";") || has(l, " = ") || has(l, "=>") || has(l, "::")) { return true }
            return (starts(l, "{") && ends(l, "}") && has(l, ":")) || (starts(l, "<") && ends(l, ">") && has(l, "</"))
        }
        let keywords = ["function ","const ","let ","var ","return ","import ","export ","def ","class ","fn ","pub ","#include","package ","func ","if (","for (","while (","} else","public ","private ","async ","await ","SELECT ","=> ","struct ","impl ","interface ","type "]
        var score = 0
        for l in lines {
            let s = RustText.trimEnd(l), trimmed = RustText.trimStart(s)
            if [";", "{", "}", "};", "):"].contains(where: { ends(s, $0) }) { score += 2 }
            if starts(l, "    ") || starts(l, "\t") { score += 1 }
            if keywords.contains(where: { starts(trimmed, $0) }) || starts(trimmed, "//") || (starts(trimmed, "# ") && code) { score += 2 }
        }
        let words = RustText.splitWhitespace(t)
        let prose = Double(words.filter { $0.unicodeScalars.allSatisfy(\.properties.isAlphabetic) }.count) / Double(max(1, words.count))
        if code { score += lines.count }
        return score >= max(lines.count, 3) && (prose < 0.85 || code)
    }
    /// Cuts text on a Unicode scalar boundary, as Rust `char` does.
    public static func excerpt(_ text: String, limit: Int) -> String { String(String.UnicodeScalarView(text.unicodeScalars.prefix(max(0,limit)))) }
    static func secretOf(_ kind: ClipKind, _ text: String?) -> SecretKind? {
        [.text,.code,.link,.other].contains(kind) ? text.flatMap(Secrets.detect) : nil
    }
}
