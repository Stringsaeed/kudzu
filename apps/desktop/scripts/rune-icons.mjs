#!/usr/bin/env node
// Generates the native app's icons from the lucide-react version the web UI ships, so both draw
// the same glyphs. Takes every icon `components/` and `app/` import from "lucide-react", plus
// EXTRA (icons the native shell adds, such as the tray's).
//
//   node scripts/rune-icons.mjs          writes src-tauri/crates/kudzu-app/src/ui/icons.rs
//   node scripts/rune-icons.mjs --check  exits 1 when the file is stale (CI)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const out = join(root, "src-tauri/crates/kudzu-app/src/ui/icons.rs")
const EXTRA = ["Keyboard", "Clipboard", "Power", "CircleAlert"]

const require = createRequire(join(root, "package.json"))
const pkg = dirname(require.resolve("lucide-react/package.json"))
const version = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8")).version

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* files(p)
    else if (/\.(tsx?|mjs)$/.test(name)) yield p
  }
}

const used = new Set(EXTRA)
for (const dir of ["components", "app"]) {
  for (const file of files(join(root, dir))) {
    const src = readFileSync(file, "utf8")
    for (const m of src.matchAll(/import\s*\{([^}]+)\}\s*from\s*"lucide-react"/g)) {
      for (const part of m[1].split(",")) {
        const name = part.trim().split(/\s+as\s+/)[0]
        if (name && name !== "type" && !name.startsWith("type ") && name !== "LucideIcon") used.add(name)
      }
    }
  }
}

// lucide-react's index maps every export name (including aliases like Loader2, CheckIcon) to a file.
const index = readFileSync(join(pkg, "dist/esm/lucide-react.mjs"), "utf8")
const fileOf = new Map()
for (const m of index.matchAll(/export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
  for (const part of m[1].split(",")) {
    const alias = part.trim().split(/\s+as\s+/)[1]
    if (alias) fileOf.set(alias.trim(), m[2])
  }
}

const attrs = (o) =>
  Object.entries(o)
    .filter(([k]) => k !== "key")
    .map(([k, v]) => `${k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase())}="${v}"`)
    .join(" ")

const icons = new Map()
for (const name of [...used].sort()) {
  const file = fileOf.get(name)
  if (!file) throw new Error(`lucide-react has no icon ${name}`)
  const { __iconData } = await import(pathToFileURL(join(pkg, "dist/esm/icons", `${file}.mjs`)).href)
  const body = __iconData.node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join("")
  icons.set(file, { body, names: [...(icons.get(file)?.names ?? []), name] })
}

const constName = (file) => file.toUpperCase().replaceAll("-", "_")
const rust = `// @generated by scripts/rune-icons.mjs from lucide-react ${version} (ISC). Do not edit.
// Add an icon by importing it in the web UI (or to EXTRA in the script), then run
// \`node scripts/rune-icons.mjs\`.

use rune::Icon;

${[...icons.entries()]
  .map(
    ([file, { body, names }]) => `/// lucide \`${file}\` (${names.join(", ")}).
pub static ${constName(file)}: Icon = Icon {
    name: "lucide-${file}",
    view: 24.0,
    body: r#"<g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</g>"#,
};`,
  )
  .join("\n\n")}
`

if (process.argv.includes("--check")) {
  let current = ""
  try { current = readFileSync(out, "utf8") } catch {}
  if (current !== rust) {
    console.error(`${out} is stale: run node scripts/rune-icons.mjs`)
    process.exit(1)
  }
} else {
  writeFileSync(out, rust)
  console.log(`wrote ${out} (${icons.size} icons)`)
}
