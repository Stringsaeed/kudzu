#!/usr/bin/env node
// Generates the native app's design tokens from app/globals.css, so the Rune UI and the web UI
// share one source: every colour (OKLCH, as authored) and every elevation layer (`--elev-*`).
//
//   node scripts/rune-tokens.mjs          writes src-tauri/crates/kudzu-app/src/ui/theme/tokens.rs
//   node scripts/rune-tokens.mjs --check  exits 1 when the file is stale (CI)
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const css = readFileSync(join(root, "app/globals.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "")
const out = join(root, "src-tauri/crates/kudzu-app/src/ui/theme/tokens.rs")

/** Declarations of every top-level rule whose selector is exactly `selector`, in order. */
function block(selector) {
  const vars = {}
  const re = /([^{}]+)\{([^{}]*)\}/g
  for (let m; (m = re.exec(css)); ) {
    if (m[1].trim() !== selector) continue
    for (const decl of m[2].split(";")) {
      const i = decl.indexOf(":")
      if (i < 0) continue
      const name = decl.slice(0, i).trim()
      if (name.startsWith("--")) vars[name.slice(2)] = decl.slice(i + 1).trim().replace(/\s+/g, " ")
    }
  }
  return vars
}

const light = block(":root")
const dark = { ...light, ...block(".dark") }
const vibrantLight = { ...light, ...block(".vibrant") }
const vibrantDark = { ...dark, ...block(".vibrant.dark") }

function resolve(value, vars, depth = 0) {
  if (depth > 8) throw new Error(`var() cycle in ${value}`)
  return value.replace(/var\(--([a-z0-9-]+)\)/g, (_, name) => {
    if (!(name in vars)) throw new Error(`unknown token --${name}`)
    return resolve(vars[name], vars, depth + 1)
  })
}

const num = (s) => {
  const t = s.trim()
  if (t.endsWith("%")) return Number(t.slice(0, -1)) / 100
  const n = Number(t.replace(/px$/, ""))
  if (Number.isNaN(n)) throw new Error(`not a number: ${s}`)
  return n
}
const f = (n) => {
  const s = String(Math.round(n * 10000) / 10000)
  return s.includes(".") ? s : `${s}.0`
}

/** `oklch(L C H)` or `oklch(L C H / A)` to a Rust expression. */
function color(src) {
  const m = /^oklch\(\s*([^)]+)\)$/.exec(src.trim())
  if (!m) throw new Error(`not an oklch colour: ${src}`)
  const [lch, a = "1"] = m[1].split("/")
  const [l, c, h] = lch.trim().split(/\s+/).map(num)
  return `oklcha(${f(l)}, ${f(c)}, ${f(h)}, ${f(num(a))})`
}

/** A CSS box-shadow list to Rust `Shadow` literals. */
function shadows(src) {
  const layers = []
  let depth = 0, start = 0
  for (let i = 0; i < src.length; i++) {
    if (src[i] === "(") depth++
    else if (src[i] === ")") depth--
    else if (src[i] === "," && depth === 0) { layers.push(src.slice(start, i)); start = i + 1 }
  }
  layers.push(src.slice(start))
  return layers.map((layer) => {
    let rest = layer.trim()
    const inset = rest.startsWith("inset ")
    if (inset) rest = rest.slice(6)
    const ci = rest.indexOf("oklch(")
    const c = color(rest.slice(ci))
    const [x = 0, y = 0, blur = 0, spread = 0] = rest.slice(0, ci).trim().split(/\s+/).map(num)
    return `Shadow { x: ${f(x)}, y: ${f(y)}, blur: ${f(blur)}, spread: ${f(spread)}, color: ${c}, inset: ${inset} }`
  })
}

const COLORS = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground", "primary",
  "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground", "accent",
  "accent-foreground", "destructive", "border", "input", "ring", "chart-1", "chart-2", "chart-3", "chart-4",
  "chart-5", "sidebar", "sidebar-foreground", "sidebar-primary", "sidebar-primary-foreground", "sidebar-accent",
  "sidebar-accent-foreground", "sidebar-border", "sidebar-ring", "surface", "surface-raised", "hairline", "faint",
  "iris", "iris-soft", "iris-foreground", "iris-contrast", "chip-time", "chip-clipboard", "chip-cursor", "chip-form",
  "chip-error", "chip-neutral", "success", "warning", "favorite",
]
const SHADOWS = Object.keys(light).filter((k) => k.startsWith("elev-"))
const rust = (name) => name.replaceAll("-", "_")

function tokens(vars) {
  const lines = []
  for (const name of COLORS) lines.push(`        ${rust(name)}: ${color(resolve(vars[name], vars))},`)
  for (const name of SHADOWS) {
    lines.push(`        ${rust(name)}: vec![\n${shadows(resolve(vars[name], vars)).map((s) => `            ${s},`).join("\n")}\n        ],`)
  }
  return lines.join("\n")
}

const motion = (name) => num(light[name].replace("ms", "")) / 1000
const radius = num(light.radius.replace("rem", "")) * 16

const file = `// @generated by scripts/rune-tokens.mjs from app/globals.css. Do not edit.
// Change the CSS, then run \`node scripts/rune-tokens.mjs\`.

use rune::{oklcha, Color, Shadow};

/// Every Kudzu design token, for one appearance.
#[derive(Clone, Debug)]
pub struct Tokens {
${COLORS.map((n) => `    pub ${rust(n)}: Color,`).join("\n")}
${SHADOWS.map((n) => `    pub ${rust(n)}: Vec<Shadow>,`).join("\n")}
}

/// \`--radius\` in points (0.625rem at 16 px).
pub const RADIUS: f32 = ${f(radius)};
/// \`--motion-fast\`, \`--motion-moderate\` and \`--motion-slow\`, in seconds.
pub const MOTION_FAST: f32 = ${f(motion("motion-fast"))};
pub const MOTION_MODERATE: f32 = ${f(motion("motion-moderate"))};
pub const MOTION_SLOW: f32 = ${f(motion("motion-slow"))};

/// \`:root\` (light), \`.dark\`, and each with \`.vibrant\` (the main window over native vibrancy).
pub fn build(dark: bool, vibrant: bool) -> Tokens {
    match (dark, vibrant) {
        (false, false) => Tokens {
${tokens(light)}
        },
        (true, false) => Tokens {
${tokens(dark)}
        },
        (false, true) => Tokens {
${tokens(vibrantLight)}
        },
        (true, true) => Tokens {
${tokens(vibrantDark)}
        },
    }
}
`.replace(/\n {8}(\w+): /g, "\n            $1: ").replace(/\n {12}(Shadow)/g, "\n                $1").replace(/\n {8}\],/g, "\n            ],")

if (process.argv.includes("--check")) {
  let current = ""
  try { current = readFileSync(out, "utf8") } catch {}
  if (current !== file) {
    console.error(`${out} is stale: run node scripts/rune-tokens.mjs`)
    process.exit(1)
  }
} else {
  writeFileSync(out, file)
  console.log(`wrote ${out} (${COLORS.length} colours, ${SHADOWS.length} elevations × 4 appearances)`)
}
