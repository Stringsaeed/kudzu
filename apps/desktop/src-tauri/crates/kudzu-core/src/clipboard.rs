/// What kind of thing was copied. Decides the icon, preview and filters.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ClipKind {
    Text,
    Code,
    Link,
    Color,
    Image,
    File,
    Other,
}

/// The app that was frontmost when something was copied.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipSource {
    pub bundle_id: String,
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
}

/// Pixel size of a copied image.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ImageSize {
    pub width: u32,
    pub height: u32,
}

/// One remembered copy. Repeats of the same content update this entry instead of adding rows.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ClipEntry {
    pub id: Uuid,
    pub kind: ClipKind,
    /// Plain text, cut to [`TEXT_EXCERPT_LIMIT`] characters (the blob has all of it).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    /// Characters in the full text.
    #[serde(default)]
    pub text_len: usize,
    /// Lines in the full text.
    #[serde(default)]
    pub line_count: usize,
    /// Copied files and folders, as absolute paths.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub files: Vec<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image: Option<ImageSize>,
    /// A CSS colour when the text is one.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub color: Option<String>,
    /// Whether formatted text (RTF or HTML) came along with the plain text.
    #[serde(default)]
    pub rich: bool,
    /// Every pasteboard type of the first item, for the "Formats" detail.
    #[serde(default)]
    pub types: Vec<String>,
    /// Bytes across all items and types.
    #[serde(default)]
    pub size: u64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<ClipSource>,
    /// Content fingerprint used to fold repeats together (FNV-1a, hex).
    pub hash: String,
    pub first_copied_at: DateTime<Utc>,
    /// Most recent copy; the history is ordered by this.
    pub copied_at: DateTime<Utc>,
    /// Times this content was copied (including the first).
    pub copy_count: u32,
    /// The most recent [`MAX_TIMINGS`] copy times, oldest first.
    #[serde(default)]
    pub timings: Vec<DateTime<Utc>>,
    /// Last time it was copied or pasted back from Kudzu.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_used_at: Option<DateTime<Utc>>,
    #[serde(default)]
    pub use_count: u32,
    /// Pinned entries never expire.
    #[serde(default)]
    pub pinned: bool,
}

impl ClipEntry {
    /// When retention removes this entry (`None` when pinned or kept forever).
    pub fn expires_at(&self, retention_days: u32) -> Option<DateTime<Utc>> {
        if self.pinned || retention_days == 0 {
            None
        } else {
            Some(self.copied_at + Duration::days(i64::from(retention_days)))
        }
    }
}

/// A copy, understood. Produced by [`classify`] from raw pasteboard items.
#[derive(Debug, Clone, PartialEq)]
pub struct Classified {
    pub kind: ClipKind,
    /// Full plain text.
    pub text: Option<String>,
    pub files: Vec<String>,
    pub color: Option<String>,
    pub rich: bool,
    /// The preferred image type present, if any.
    pub image_type: Option<String>,
    pub types: Vec<String>,
    pub size: u64,
    pub hash: u64,
}

/// Whether the source marked this copy as private or transient (see [`uti::PRIVATE_MARKERS`]).
pub fn is_private(items: &[PasteItem]) -> bool {
    items.iter().flatten().any(|(t, _)| uti::PRIVATE_MARKERS.contains(&t.as_str()))
}

fn find<'a>(items: &'a [PasteItem], kind: &str) -> Option<&'a [u8]> {
    items.iter().flatten().find(|(t, _)| t == kind).map(|(_, d)| d.as_slice())
}

