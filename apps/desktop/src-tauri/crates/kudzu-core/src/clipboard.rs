/// Heuristic: does this text read like source code or a shell command?
pub fn looks_like_code(text: &str, source_bundle: Option<&str>) -> bool {
    let t = text.trim();
    if t.is_empty() {
        return false;
    }
    let lines: Vec<&str> = t.lines().collect();
    let from_code_app = source_bundle.is_some_and(|b| CODE_APPS.contains(&b) || b.starts_with("com.jetbrains."));
    if lines.len() == 1 {
        let l = lines[0];
        if l.starts_with("$ ") || COMMANDS.iter().any(|c| l.starts_with(c)) {
            return true;
        }
        if from_code_app && (l.contains("()") || l.ends_with(';') || l.contains(" = ") || l.contains("=>") || l.contains("::")) {
            return true;
        }
        return (l.starts_with('{') && l.ends_with('}') && l.contains(':')) || (l.starts_with("<") && l.ends_with('>') && l.contains("</"));
    }
    let mut score = 0i32;
    let keywords = [
        "function ", "const ", "let ", "var ", "return ", "import ", "export ", "def ", "class ", "fn ", "pub ", "#include", "package ", "func ", "if (", "for (", "while (",
        "} else", "public ", "private ", "async ", "await ", "SELECT ", "=> ", "struct ", "impl ", "interface ", "type ",
    ];
    for l in &lines {
        let s = l.trim_end();
        if s.ends_with(';') || s.ends_with('{') || s.ends_with('}') || s.ends_with("};") || s.ends_with("):") {
            score += 2;
        }
        if l.starts_with("    ") || l.starts_with('\t') {
            score += 1;
        }
        let trimmed = s.trim_start();
        if keywords.iter().any(|k| trimmed.starts_with(k)) || trimmed.starts_with("//") || trimmed.starts_with("# ") && from_code_app {
            score += 2;
        }
    }
    let prose = t.split_whitespace().filter(|w| w.chars().all(char::is_alphabetic)).count() as f64 / t.split_whitespace().count().max(1) as f64;
    let threshold = (lines.len() as i32).max(3);
    if from_code_app {
        score += lines.len() as i32;
    }
    score >= threshold && (prose < 0.85 || from_code_app)
}

/// Cuts `text` to at most `limit` characters on a char boundary.
pub fn excerpt(text: &str, limit: usize) -> String {
    match text.char_indices().nth(limit) {
        Some((i, _)) => text[..i].to_string(),
        None => text.to_string(),
    }
}

/// The result of recording a copy.
#[derive(Debug, Clone, PartialEq)]
pub enum Ingest {
    /// New content.
    Added(ClipEntry),
    /// Content already in the history: moved to the top with a new timing.
    Repeated(ClipEntry),
}

impl Ingest {
    pub fn entry(&self) -> &ClipEntry {
        match self {
            Ingest::Added(e) | Ingest::Repeated(e) => e,
        }
    }
}

/// The clipboard history, newest copy first.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct History {
    #[serde(default = "History::format_version")]
    pub version: u32,
    pub entries: Vec<ClipEntry>,
}

impl History {
    fn format_version() -> u32 {
        1
    }

    pub fn new() -> Self {
        Self { version: Self::format_version(), entries: vec![] }
    }

    pub fn get(&self, id: Uuid) -> Option<&ClipEntry> {
        self.entries.iter().find(|e| e.id == id)
    }

    /// Records a copy made at `now`. Repeated content keeps its id, pin and history of timings.
    pub fn ingest(&mut self, c: &Classified, source: Option<ClipSource>, image: Option<ImageSize>, now: DateTime<Utc>) -> Ingest {
        let hash = format!("{:016x}", c.hash);
        let full_text = c.text.as_deref().unwrap_or_default();
        let fill = |e: &mut ClipEntry| {
            e.kind = c.kind;
            e.text = c.text.as_deref().map(|t| excerpt(t, TEXT_EXCERPT_LIMIT));
            e.text_len = full_text.chars().count();
            e.line_count = if full_text.is_empty() { 0 } else { full_text.lines().count().max(1) };
            e.files = c.files.clone();
            e.color = c.color.clone();
            e.rich = c.rich;
            e.types = c.types.clone();
            e.size = c.size;
            if image.is_some() {
                e.image = image;
            }
        };
        if let Some(pos) = self.entries.iter().position(|e| e.hash == hash) {
            let mut e = self.entries.remove(pos);
            fill(&mut e);
            e.copied_at = now;
            e.copy_count = e.copy_count.saturating_add(1);
            e.timings.push(now);
            if e.timings.len() > MAX_TIMINGS {
                let drop = e.timings.len() - MAX_TIMINGS;
                e.timings.drain(..drop);
            }
            if source.is_some() {
                e.source = source;
            }
            self.entries.insert(0, e.clone());
            return Ingest::Repeated(e);
        }
        let mut e = ClipEntry {
            id: Uuid::new_v4(),
            kind: c.kind,
            text: None,
            text_len: 0,
            line_count: 0,
            files: vec![],
            image: None,
            color: None,
            rich: false,
            types: vec![],
            size: 0,
            source,
            hash,
            first_copied_at: now,
            copied_at: now,
            copy_count: 1,
            timings: vec![now],
            last_used_at: None,
            use_count: 0,
            pinned: false,
        };
        fill(&mut e);
        self.entries.insert(0, e.clone());
        Ingest::Added(e)
    }

    /// Removes unpinned entries older than `retention_days` (0 keeps them) and any beyond
    /// [`MAX_ENTRIES`] unpinned ones. Returns what was removed.
    pub fn prune(&mut self, now: DateTime<Utc>, retention_days: u32) -> Vec<ClipEntry> {
        let cutoff = (retention_days > 0).then(|| now - Duration::days(i64::from(retention_days)));
        let mut kept_unpinned = 0usize;
        let mut removed = Vec::new();
        let mut kept = Vec::with_capacity(self.entries.len());
        for e in self.entries.drain(..) {
            let expired = !e.pinned && cutoff.is_some_and(|c| e.copied_at < c);
            let over = !e.pinned && kept_unpinned >= MAX_ENTRIES;
            if expired || over {
                removed.push(e);
            } else {
                if !e.pinned {
                    kept_unpinned += 1;
                }
                kept.push(e);
            }
        }
        self.entries = kept;
        removed
    }

    /// Removes entries by id, returning them (in history order).
    pub fn remove(&mut self, ids: &[Uuid]) -> Vec<ClipEntry> {
        let (gone, kept) = self.entries.drain(..).partition(|e| ids.contains(&e.id));
        self.entries = kept;
        gone
    }

    /// Puts removed entries back in time order (undo). Ids already present are skipped.
    pub fn restore(&mut self, entries: Vec<ClipEntry>) -> Vec<ClipEntry> {
        let mut restored = Vec::new();
        for e in entries {
            if self.entries.iter().any(|x| x.id == e.id || x.hash == e.hash) {
                continue;
            }
            restored.push(e.clone());
            self.entries.push(e);
        }
        self.entries.sort_by_key(|e| std::cmp::Reverse(e.copied_at));
        restored
    }

    /// Removes everything (pinned too when `include_pinned`), returning what was removed.
    pub fn clear(&mut self, include_pinned: bool) -> Vec<ClipEntry> {
        let (gone, kept) = self.entries.drain(..).partition(|e| include_pinned || !e.pinned);
        self.entries = kept;
        gone
    }

    pub fn set_pinned(&mut self, id: Uuid, pinned: bool) -> Option<ClipEntry> {
        let e = self.entries.iter_mut().find(|e| e.id == id)?;
        e.pinned = pinned;
        Some(e.clone())
    }

    /// Notes that the user put this entry back on the clipboard; it moves to the top.
    pub fn mark_used(&mut self, id: Uuid, now: DateTime<Utc>) -> Option<ClipEntry> {
        let pos = self.entries.iter().position(|e| e.id == id)?;
        let mut e = self.entries.remove(pos);
        e.last_used_at = Some(now);
        e.use_count = e.use_count.saturating_add(1);
        e.copied_at = now;
        self.entries.insert(0, e.clone());
        Some(e)
    }
}

const BLOB_MAGIC: &[u8; 4] = b"KZC1";

/// Serializes pasteboard items: magic, then per item a type count and `(type, data)` pairs,
/// every length a little-endian u32/u64.
pub fn encode_items(items: &[PasteItem]) -> Vec<u8> {
    let size: usize = items.iter().flatten().map(|(t, d)| t.len() + d.len() + 12).sum();
    let mut out = Vec::with_capacity(size + 8);
    out.extend_from_slice(BLOB_MAGIC);
    out.extend_from_slice(&(items.len() as u32).to_le_bytes());
    for item in items {
        out.extend_from_slice(&(item.len() as u32).to_le_bytes());
        for (t, d) in item {
            out.extend_from_slice(&(t.len() as u32).to_le_bytes());
            out.extend_from_slice(t.as_bytes());
            out.extend_from_slice(&(d.len() as u64).to_le_bytes());
            out.extend_from_slice(d);
        }
    }
    out
}

/// Inverse of [`encode_items`]; `None` on any malformed input.
pub fn decode_items(bytes: &[u8]) -> Option<Vec<PasteItem>> {
    struct Reader<'a>(&'a [u8]);
    impl<'a> Reader<'a> {
        fn take(&mut self, n: usize) -> Option<&'a [u8]> {
            if self.0.len() < n {
                return None;
            }
            let (a, b) = self.0.split_at(n);
            self.0 = b;
            Some(a)
        }
        fn u32(&mut self) -> Option<usize> {
            Some(u32::from_le_bytes(self.take(4)?.try_into().ok()?) as usize)
        }
        fn u64(&mut self) -> Option<usize> {
            usize::try_from(u64::from_le_bytes(self.take(8)?.try_into().ok()?)).ok()
        }
    }
    let mut r = Reader(bytes);
    if r.take(4)? != BLOB_MAGIC {
        return None;
    }
    let count = r.u32()?;
    let mut items = Vec::with_capacity(count.min(1024));
    for _ in 0..count {
        let n = r.u32()?;
        let mut item = Vec::with_capacity(n.min(256));
        for _ in 0..n {
            let tl = r.u32()?;
            let t = std::str::from_utf8(r.take(tl)?).ok()?.to_string();
            let dl = r.u64()?;
            item.push((t, r.take(dl)?.to_vec()));
        }
        items.push(item);
    }
    r.0.is_empty().then_some(items)
}

/// Full plain text of decoded items, if any.
pub fn text_of(items: &[PasteItem]) -> Option<String> {
    find(items, uti::PLAIN_TEXT).or_else(|| find(items, uti::LEGACY_TEXT)).and_then(|d| String::from_utf8(d.to_vec()).ok())
}

/// Bytes and MIME type of the best image in decoded items.
pub fn image_of(items: &[PasteItem]) -> Option<(&[u8], &'static str)> {
    uti::IMAGES.iter().find_map(|(t, mime)| find(items, t).map(|d| (d, *mime)))
}

/// MIME type for an image file path a webview can display, by extension.
pub fn image_mime_for_path(path: &str) -> Option<&'static str> {
    let ext = path.rsplit_once('.')?.1.to_ascii_lowercase();
    Some(match ext.as_str() {
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "webp" => "image/webp",
        "heic" | "heif" => "image/heic",
        "tif" | "tiff" => "image/tiff",
        "bmp" => "image/bmp",
        "avif" => "image/avif",
        _ => return None,
    })
}

